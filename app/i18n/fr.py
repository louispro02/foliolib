"""French. Each key is the English text exactly as it appears in the code; the value is its French translation. The `{name}`
placeholders must be the same on both sides (a test checks it), and a text left out here is shown in English.

Write plain spaces: `typography()` below turns them into the no-break spaces that French typography wants."""


def typography(text):
    """No-break space before % ; : ? ! and inside « », so that these signs never begin a line of their own."""
    for before in (" %", " ;", " ?", " !"):
        text = text.replace(before, "\u202f" + before[1])
    return text.replace(" :", "\u00a0:").replace("« ", "«\u00a0").replace(" »", "\u00a0»")


